// resticRepo builds the restic S3 repository URL. restic requires an explicit
// scheme for non-Amazon endpoints (Cloudflare R2, Backblaze B2, MinIO…), so we
// add https:// when the endpoint has none — harmless for AWS too. The bucket is
// appended path-style, which is what restic's bucket-lookup=auto selects for any
// non-Amazon/Google host.
func resticRepo(b BucketRef) string {
	ep := strings.TrimRight(strings.TrimSpace(b.Endpoint), "/")
	if ep != "" && !strings.Contains(ep, "://") {
		ep = "https://" + ep
	}
	repo := "s3:" + ep + "/" + strings.Trim(b.Bucket, "/")
	if p := strings.Trim(b.Prefix, "/"); p != "" {
		repo += "/" + p
	}
	return repo
}

// isR2 reports whether the endpoint is a Cloudflare R2 host.
func isR2(endpoint string) bool {
	return strings.Contains(strings.ToLower(endpoint), "r2.cloudflarestorage.com")
}

// buildEnv merges new secrets over whatever already exists on the VPS (so blank
// fields on edit keep the stored value), and always refreshes the repo/region
// from the current bucket settings.
func buildEnv(b BucketRef, s Secrets, existing map[string]string) map[string]string {
	env := map[string]string{}
	for k, v := range existing {
		env[k] = v
	}
	env["RESTIC_REPOSITORY"] = resticRepo(b)
	region := strings.TrimSpace(b.Region)
	if region == "" && isR2(b.Endpoint) {
		// R2's canonical region is "auto". Setting it explicitly also bypasses
		// restic/minio-go's GetBucketLocation probe — the classic R2 init failure
		// on older restic — and is harmless on any version.
		region = "auto"
	}
	if region != "" {
		env["AWS_DEFAULT_REGION"] = region
	}
	if s.AccessKey != "" {
		env["AWS_ACCESS_KEY_ID"] = s.AccessKey
	}
	if s.SecretKey != "" {
		env["AWS_SECRET_ACCESS_KEY"] = s.SecretKey
	}
	if s.ResticPassword != "" {
		env["RESTIC_PASSWORD"] = s.ResticPassword
	}
	return env
}

// renderEnv writes KEY='value' lines (single-quoted so any character survives a
// `. file` source). readEnv reverses the quoting.
func renderEnv(env map[string]string) string {
	order := []string{"RESTIC_REPOSITORY", "RESTIC_PASSWORD", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_DEFAULT_REGION"}
	seen := map[string]bool{}
	var b strings.Builder
	emit := func(k string) {
		v, ok := env[k]
		if !ok || seen[k] {
			return
		}
		seen[k] = true
		b.WriteString(k + "=" + shellQuote(v) + "\n")
	}
	for _, k := range order {
		emit(k)
	}
	var rest []string
	for k := range env {
		if !seen[k] {
			rest = append(rest, k)
		}
	}
	sort.Strings(rest)
	for _, k := range rest {
		emit(k)
	}
	return b.String()
}

// shellUnquote reverses shellQuote for values read back from an env file.
func shellUnquote(s string) string {
	if len(s) >= 2 && s[0] == '\'' && s[len(s)-1] == '\'' {
		return strings.ReplaceAll(s[1:len(s)-1], `'\''`, `'`)
	}
	return s
}

// sanitize reduces an arbitrary name to a filename-safe token.
func sanitize(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '.', r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "x"
	}
	return b.String()
}
