package backup

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"
)

// dbDumpName is the snapshot filename for a database dump. It hashes container +
// db with a NUL joiner so two different (container, db) pairs can never collide
// onto the same file — sanitize() alone would, because it maps the separator and
// other characters to '_'. backup and restore both call this, so the names match.
func dbDumpName(container, db string) string {
	h := sha256.Sum256([]byte(container + "\x00" + db))
	return "db_" + hex.EncodeToString(h[:6]) + ".sql"
}

// sourceEnv is the snippet that loads a job's secrets and exports them so the
// child processes (restic, docker) inherit RESTIC_REPOSITORY, the S3 keys, etc.
// `set -a` makes every assignment from the sourced file an export.
func sourceEnv(id string) string {
	return "set -a; . " + shellQuote(jobEnv(id)) + "; set +a"
}

// RenderScript produces the per-job backup runner: dump databases, tar named
// volumes, copy the compose dir, then `restic backup` + `restic forget`.
// Database passwords are sniffed from the live container at run time (never
// stored), so the script stays correct even if credentials rotate.
func RenderScript(job Job) string {
	var b strings.Builder
	w := func(s string) { b.WriteString(s + "\n") }

	w("#!/bin/sh")
	w("# Generated by vps-manager. Backup job: " + job.Name + " (" + job.ID + ")")
	w("set -e")
	w("export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin")
	w(sourceEnv(job.ID))
	w(`STAGE="$(mktemp -d /tmp/vps-bak.XXXXXX)"`)
	w(`START=$(date +%s)`)
	// Heartbeat: a background loop so long, quiet steps (a big volume tar, or the
	// restic upload — which prints nothing to a non-terminal pipe) still show a
	// pulse with the staged size and elapsed time, instead of looking frozen.
	w(`( while true; do sleep 10; echo "  … working — staged $(du -sh "$STAGE" 2>/dev/null | cut -f1), $(( $(date +%s) - START ))s elapsed"; done ) & HB=$!`)
	w(`trap 'kill "$HB" 2>/dev/null; rm -rf "$STAGE"' EXIT`)
	w(`echo "[$(date -Is 2>/dev/null || date)] backup ` + job.ID + ` starting"`)

	if job.IncludeCompose && job.StackPath != "" {
		w("")
		w("echo '→ copying compose directory'")
		w(`mkdir -p "$STAGE/compose"`)
		w("cp -a " + shellQuote(strings.TrimRight(job.StackPath, "/")+"/.") + ` "$STAGE/compose/" 2>/dev/null || echo '  (nothing to copy)'`)
	}

	for _, d := range job.Databases {
		w("")
		w("echo " + shellQuote("→ dumping "+d.Engine+" database "+d.DB+" from "+d.Container))
		out := `"$STAGE/` + dbDumpName(d.Container, d.DB) + `"`
		c := shellQuote(d.Container)
		switch d.Engine {
		case "postgres":
			w(`PW="$(docker exec ` + c + ` printenv POSTGRES_PASSWORD 2>/dev/null || true)"`)
			w("docker exec -e PGPASSWORD=\"$PW\" " + c + " pg_dump -U " + shellQuote(d.User) + " " + shellQuote(d.DB) + " > " + out)
		case "mysql":
			w(`PW="$(docker exec ` + c + ` printenv MYSQL_ROOT_PASSWORD 2>/dev/null || true)"`)
			w(`[ -n "$PW" ] || PW="$(docker exec ` + c + ` printenv MYSQL_PASSWORD 2>/dev/null || true)"`)
			w("docker exec -e MYSQL_PWD=\"$PW\" " + c + " mysqldump -u " + shellQuote(d.User) + " " + shellQuote(d.DB) + " > " + out)
		}
		w(`echo "    ✓ dumped ($(du -h ` + out + ` 2>/dev/null | cut -f1))"`)
	}

	for _, vol := range job.Volumes {
		w("")
		w("echo " + shellQuote("→ archiving volume "+vol))
		archive := `"/dest/vol_` + sanitize(vol) + `.tar.gz"`
		host := `"$STAGE/vol_` + sanitize(vol) + `.tar.gz"`
		w("docker run --rm -v " + shellQuote(vol) + `:/src:ro -v "$STAGE":/dest alpine tar czf ` + archive + " -C /src .")
		w(`echo "    ✓ archived ($(du -h ` + host + ` 2>/dev/null | cut -f1))"`)
	}

	w("")
	w(`echo "→ uploading $(du -sh "$STAGE" 2>/dev/null | cut -f1) to the bucket with restic…"`)
	w(`restic backup "$STAGE" --tag vps-manager --tag ` + shellQuote(job.ID))
	if forget := forgetFlags(job.Retention); forget != "" {
		w("echo '→ applying retention'")
		w("restic forget " + forget + " --prune")
	}
	w(`echo "[$(date -Is 2>/dev/null || date)] backup ` + job.ID + ` done"`)
	return b.String()
}

// RenderCron is the /etc/cron.d drop-in: run as root, append output to a log.
func RenderCron(job Job) string {
	return fmt.Sprintf("%s  root  %s >> %s 2>&1\n",
		strings.TrimSpace(job.Schedule), jobScript(job.ID), logFile(job.ID))
}

// forgetFlags turns a retention policy into restic forget flags (empty if none).
func forgetFlags(r RetentionPolicy) string {
	var f []string
	if r.KeepLast > 0 {
		f = append(f, fmt.Sprintf("--keep-last %d", r.KeepLast))
	}
	if r.KeepDaily > 0 {
		f = append(f, fmt.Sprintf("--keep-daily %d", r.KeepDaily))
	}
	if r.KeepWeekly > 0 {
		f = append(f, fmt.Sprintf("--keep-weekly %d", r.KeepWeekly))
	}
	if r.KeepMonthly > 0 {
		f = append(f, fmt.Sprintf("--keep-monthly %d", r.KeepMonthly))
	}
	return strings.Join(f, " ")
}

